def test_frontmatter_follows_the_agent_skills_format() -> None:
    assert FRONTMATTER.startswith("---\n")
    info = skill_info(SKILL)
    assert info.name == SKILL_NAME == bundled().name
    assert re.fullmatch(r"[a-z0-9-]{1,64}", SKILL_NAME)
    description = re.search(r"^description: >-\n((?:  .*\n?)+)", FRONTMATTER, re.M)
    assert description is not None
    text = " ".join(line.strip() for line in description[1].splitlines())
    assert 0 < len(text) <= 1024
    assert "<" not in text
    assert ">" not in text


def test_version_is_the_package_version() -> None:
    assert skill_info(SKILL).version == politefetch.__version__


def test_skill_stays_short() -> None:
    assert len(SKILL.splitlines()) <= 500


