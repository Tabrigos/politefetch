# --- the hand-written guide matches the code ---------------------------------


def test_dotted_paths_resolve() -> None:
    paths = set(re.findall(r"\bpolitefetch(?:\.\w+)+", BODY))
    assert paths
    for path in paths:
        module, _, attr = path.rpartition(".")
        try:
            target = importlib.import_module(path)
        except ImportError:
            target = getattr(importlib.import_module(module), attr)
        assert target is not None, path


def test_names_in_inline_code_exist() -> None:
    known = _public_names()
    unknown: set[str] = set()
    for span in INLINE.findall(PROSE):
        if "/" in span or " " in span.split("(")[0].strip():
            continue  # paths, shell commands, prose in code
        if re.search(r"\.(json|db|md|toml)$", span) or span == "metadata.version":
            continue  # file names, the frontmatter
        if span.startswith("["):
            continue  # a TOML table
        span = re.sub(r'"[^"]*"', '""', span)  # string values are not names
        words = re.findall(r"\.([A-Za-z_]\w*)|([A-Za-z_]\w*)\(|([A-Za-z_]\w*)=", span)
        for groups in words:
            word = next(g for g in groups if g)
            if word not in known:
                unknown.add(f"{word} (in `{span}`)")
    assert not unknown, sorted(unknown)


def _parameters_by_name() -> dict[str, set[str]]:
    """For each public function or method name, the parameters of every
    callable with that name."""
    found: dict[str, set[str]] = {}
    for module_name in _public_modules():
        module = importlib.import_module(module_name)
        for name in getattr(module, "__all__", []):
            value = getattr(module, name)
            members = [(name, value)]
            if inspect.isclass(value):
                members += [
                    (n, m)
                    for n, m in inspect.getmembers(value)
                    if not n.startswith("_")
                ]
            for member_name, member in members:
                params = _parameters(member)
                if params:
                    found.setdefault(member_name, set()).update(params)
    return found


def test_keyword_arguments_belong_to_their_call() -> None:
    known = _parameters_by_name()
    spans = re.findall(r"`([^`]+)`", PROSE)  # code spans, over line breaks too
    wrong = set()
    for span in spans:
        for call, args in re.findall(r"(\w+)\(([^()]*)\)", span.replace("\n", " ")):
            if call not in known:
                continue
            for keyword in re.findall(r"(\w+)=", re.sub(r'"[^"]*"', '""', args)):
                if keyword not in known[call]:
                    wrong.add(f"{call}({keyword}=)")
    assert not wrong, sorted(wrong)


