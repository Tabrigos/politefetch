def test_skill_module_is_the_shared_template() -> None:
    source = Path(inspect.getfile(skill)).read_bytes().replace(b"\r\n", b"\n")
    shared = source.split(b"# ---- nothing below this line", 1)
    assert len(shared) == 2, "the line that separates the constants is missing"
    fingerprint = "sha256:" + hashlib.sha256(shared[1]).hexdigest()
    assert fingerprint == SCHEMA_FINGERPRINT, "copy skill/__init__.py from the template"


def test_install_writes_a_marked_copy_that_check_accepts(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    target = tmp_path / ".claude" / "skills" / SKILL_DIR.name
    assert skill.main(["install", "--target", str(target)]) == 0
    assert (target / "SKILL.md").read_bytes() == (SKILL_DIR / "SKILL.md").read_bytes()
    marker = json.loads((target / skill.MARKER).read_text(encoding="utf-8"))
    assert marker["hash"] == skill.content_hash(SKILL_DIR)
    assert marker["versione"] == package.__version__
    assert skill.main(["check", "--target", str(target)]) == 0
    crlf = (target / "SKILL.md").read_bytes().replace(b"\n", b"\r\n")
    (target / "SKILL.md").write_bytes(crlf)
    assert skill.main(["check", "--target", str(target)]) == 0  # line endings only
    (target / "SKILL.md").write_bytes(crlf + b"local edit\r\n")
    assert skill.main(["check", "--target", str(target)]) == 1
    assert "by hand" in capsys.readouterr().out


def test_install_refuses_other_places_and_unmarked_directories(tmp_path: Path) -> None:
    elsewhere = tmp_path / "elsewhere"
    assert skill.main(["install", "--target", str(elsewhere)]) == 1
    assert not elsewhere.exists()
    mine = tmp_path / ".claude" / "skills" / SKILL_DIR.name
    mine.mkdir(parents=True)
    (mine / "notes.md").write_text("keep", encoding="utf-8")
    assert skill.main(["install", "--target", str(mine)]) == 1
    assert (mine / "notes.md").read_text(encoding="utf-8") == "keep"


def test_path_and_show(capsys: pytest.CaptureFixture[str]) -> None:
    assert skill.main(["path"]) == 0
    assert Path(capsys.readouterr().out.strip()) == SKILL_DIR
