"""The bundled agent skill is current, accurate, and installable.

``SKILL.md`` is written by hand, ``references/api.md`` is generated by
``tools/build_skill.py``. These tests fail when either falls behind the code:
a stale reference, a public module or name left out of it, a version that is
not the package's, a name that does not exist, an example that does not run.
"""

import contextlib
import importlib
import inspect
import pkgutil
import re
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

import build_skill
import pytest

import politefetch
from politefetch.clock import FakeClock
from politefetch.errors import RefusalReason
from politefetch.gate import Gate
from politefetch.skill import (
    DEFAULT_TARGET,
    SKILL_NAME,
    bundled,
    check,
    install,
    main,
    read_skill,
    skill_info,
)
from politefetch.store import MemoryStore
from politefetch.testing.simulator import Respond, SourceSimulator

SKILL = read_skill()
FRONTMATTER, BODY = SKILL.split("\n---\n", 1)
FENCE = re.compile(r"^```(\w*)\n(.*?)^```$", re.MULTILINE | re.DOTALL)
PROSE = FENCE.sub("", BODY)
INLINE = re.compile(r"`([^`\n]+)`")
T = datetime(2026, 10, 16, 12, 0, tzinfo=UTC)


def _blocks(kind: str) -> list[str]:
    return [body for k, body in FENCE.findall(BODY) if k == kind]


def _public_modules() -> list[str]:
    found = ["politefetch"]
    for info in pkgutil.walk_packages(politefetch.__path__, "politefetch."):
        if not any(part.startswith("_") for part in info.name.split(".")):
            found.append(info.name)
    return sorted(found)


def _parameters(value: object) -> set[str]:
    target = value.fget if isinstance(value, property) else value
    if not callable(target):
        return set()
    with contextlib.suppress(TypeError, ValueError):
        return set(inspect.signature(target).parameters)
    return set()


def _public_names() -> set[str]:
    """Every module, class, function, method, attribute and parameter name a
    reader of the skill could use."""
    names: set[str] = set()
    for module_name in _public_modules():
        module = importlib.import_module(module_name)
        names |= set(module_name.split("."))
        for name in getattr(module, "__all__", []):
            value = getattr(module, name)
            names |= {name} | _parameters(value)
            names |= {n for n in dir(value) if not n.startswith("__")}
            if inspect.isclass(value):
                for member in vars(value).values():
                    names |= _parameters(member)
    return names | {"source_simulator", "network_barrier", "politefetch_barrier"}


