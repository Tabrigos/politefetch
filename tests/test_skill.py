def test_the_built_wheel_ships_the_skill() -> None:
    pattern = os.environ.get("SKILL_WHEEL", "")
    if pattern and not os.path.isabs(pattern):
        pattern = str(ROOT / pattern)  # relative to the library, not to the cwd
    found = sorted(glob.glob(pattern)) if pattern else []
    if not found:
        if os.environ.get("CI"):
            pytest.fail("CI must build the wheel and set SKILL_WHEEL=dist/*.whl")
        pytest.skip("SKILL_WHEEL not set: build the wheel to check it (required in CI)")
    version = package.__version__.replace("-", "_")
    wheels = [w for w in found if Path(w).name.split("-")[1:2] == [version]]
    assert wheels, f"no wheel of version {package.__version__} in {found}"
    prefix = f"{PACKAGE}/skill/{SKILL_DIR.name}/"
    expected = {prefix + p.relative_to(SKILL_DIR).as_posix() for p in _skill_files()}
    for wheel in wheels:
        names = set(zipfile.ZipFile(wheel).namelist())
        assert not expected - names, (Path(wheel).name, sorted(expected - names))
