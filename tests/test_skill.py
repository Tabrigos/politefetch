"""The agent skill shipped with the package is current, accurate and shipped.

``SKILL.md`` is written by hand, ``references/api.md`` is generated by
``tools/build_skill.py``. Each test fails for one precise reason: a stale
reference, a public module or name left out, a name that does not exist, an
example that does not run, a version that is not the package's, CRLF line
endings, a wheel without the skill, a changed copy of the shared module. None
can pass on an empty input.

A copy of the shared template (schema 1): only the constants above the line
change from one library to another.
"""

from __future__ import annotations

import builtins
import glob
import hashlib
import importlib
import inspect
import json
import keyword
import os
import re
import sys
import zipfile
from pathlib import Path
from typing import Any

import pytest

PACKAGE = "politefetch"
"""The import name of the package."""

MIN_EXAMPLES = 3
"""Python blocks that SKILL.md must contain; all of them are executed, except
those fenced ```` ```python nocheck ```` (a fragment, a call that needs a network)."""

NOT_API: set[str] = {
    "metadata.version",
    "timedelta",  # the standard library's
}
"""Spans in backticks that look like names but are not the library's API."""

# ---- nothing below this line changes between libraries ----------------------

SCHEMA_FINGERPRINT = (
    "sha256:babbb17f57cf7027fbe3f35f03549e8b500f45ef37117f5bfa4bf6c19550dc25"
)
"""Fingerprint of the shared part of ``<package>/skill/__init__.py``."""

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import build_skill  # noqa: E402

package = importlib.import_module(PACKAGE)
skill = importlib.import_module(f"{PACKAGE}.skill")
SKILL_DIR: Path = skill.bundled()
SKILL = (SKILL_DIR / "SKILL.md").read_text(encoding="utf-8")
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
FENCE = re.compile(r"^```(\w*)([^\n]*)\n(.*?)^```[ \t]*$", re.MULTILINE | re.DOTALL)
INLINE = re.compile(r"`([^`\n]+)`")
BODY = SKILL.split("\n---\n", 1)[-1]
PROSE = FENCE.sub("", BODY)
PORTABLE = {
    "name",
    "description",
    "license",
    "compatibility",
    "metadata",
    "allowed-tools",
}


def _skill_files() -> list[Path]:
    files = [
        p
        for p in SKILL_DIR.rglob("*")
        if p.is_file()
        and "__pycache__" not in p.parts
        and p.suffix not in {".pyc", ".pyo"}
    ]
    assert len(files) >= 2, f"{SKILL_DIR} should hold SKILL.md and references/"
    return files


def _frontmatter() -> dict[str, Any]:
    match = FRONTMATTER.match(SKILL)
    assert match, "SKILL.md must start with a --- frontmatter block"
    fields: dict[str, Any] = {}
    key = ""
    for line in match[1].splitlines():
        top = re.match(r"^([A-Za-z][\w-]*):[ \t]*(.*)$", line)
        if top:
            key, value = top[1], top[2].strip()
            if value == "":
                fields[key] = {}
            elif value in {">", ">-", "|", "|-"}:
                fields[key] = ""
            else:
                fields[key] = value.strip("\"'")
        elif key and line.startswith((" ", "\t")):
            if isinstance(fields[key], dict):
                pair = re.match(r"^\s+([\w.-]+):\s*[\"']?(.*?)[\"']?\s*$", line)
                assert pair, f"metadata holds string pairs only: {line!r}"
                fields[key][pair[1]] = pair[2]
            else:
                fields[key] = f"{fields[key]} {line.strip()}".strip()
    return fields


def _blocks(*kinds: str) -> list[str]:
    return [
        code
        for kind, info, code in FENCE.findall(BODY)
        if kind in kinds and "nocheck" not in info.split()
    ]


def _import(module_name: str) -> Any:
    """Import a public module; one of ``EXTRA`` without its extra skips the test."""
    if module_name in build_skill.EXTRA:
        reason = f"needs {build_skill.EXTRA[module_name]}"
        reason += ": the skill tests run with every extra installed"
        return pytest.importorskip(module_name, reason=reason)
    return importlib.import_module(module_name)


# --- frontmatter, size, layout ---------------------------------------------------


def test_frontmatter_is_portable_agent_skills() -> None:
    fields = _frontmatter()
    assert set(fields) <= PORTABLE, f"not portable: {sorted(set(fields) - PORTABLE)}"
    name = fields["name"]
    assert name == SKILL_DIR.name
    assert len(name) <= 64
    assert re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name), name
    assert "claude" not in name
    assert "anthropic" not in name
    description = fields["description"]
    assert 50 <= len(description) <= 1024, len(description)
    assert "<" not in description
    assert ">" not in description
    when = r"\buse(?: it| this(?: skill)?)? when(?:ever)?\b"
    quando = r"\busa(?:re|rla|la) (?:quando|ogni volta che)\b"
    assert re.search(f"{when}|{quando}", description, re.I), "no 'Use when'"


def test_version_is_the_package_version_and_is_in_the_changelog() -> None:
    version = _frontmatter()["metadata"].get("version")
    assert version == package.__version__
    changelog = (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")
    heading = rf"^##\s+\[?{re.escape(version)}\]?(\s|$)"
    assert re.search(heading, changelog, re.M), f"CHANGELOG.md: no '## {version}'"


def test_skill_is_short_and_references_are_one_level_deep() -> None:
    assert len(SKILL.splitlines()) <= 500
    for path in _skill_files():
        rel = path.relative_to(SKILL_DIR).as_posix()
        assert rel == "SKILL.md" or re.fullmatch(
            r"(references|assets|scripts)/[^/]+", rel
        ), rel
        lines = (
            path.read_text(encoding="utf-8").splitlines()
            if path.suffix == ".md"
            else []
        )
        if rel.startswith("references/") and len(lines) > 100:
            head = "\n".join(lines[:20])
            index = r"^(Contents|Exports|Modules|Sections|Indice)\b"
            assert re.search(index, head, re.M), rel


def test_every_reference_is_cited_and_every_citation_exists() -> None:
    cited = set(re.findall(r"\b((?:references|assets|scripts)/[\w.-]+\w)", BODY))
    assert cited, "SKILL.md points to no reference file"
    for rel in cited:
        assert (SKILL_DIR / rel).is_file(), rel
    for path in (SKILL_DIR / "references").iterdir():
        assert f"references/{path.name}" in cited, f"references/{path.name} not cited"


def test_skill_files_have_lf_line_endings() -> None:
    crlf = [p.name for p in _skill_files() if b"\r" in p.read_bytes()]
    assert not crlf, f"CRLF in {crlf}: add '*.md text eol=lf' to .gitattributes"


