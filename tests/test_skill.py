def test_shell_commands_name_real_subcommands() -> None:
    lines = [
        line
        for line in "".join(_blocks("bash")).splitlines()
        if "politefetch.skill" in line
    ]
    assert lines
    for line in lines:
        command = line.split("#")[0].split()[3:]
        with pytest.raises(SystemExit) as exit_:
            main([*command, "--help"])
        assert exit_.value.code == 0


# --- the command line ---------------------------------------------------------


def test_install_copies_the_whole_skill(tmp_path: Path) -> None:
    target = tmp_path / "skills" / SKILL_NAME
    assert install(target) == target
    assert (target / "SKILL.md").read_text("utf-8") == SKILL
    reference = bundled().joinpath("references", "api.md").read_text("utf-8")
    assert (target / "references" / "api.md").read_text("utf-8") == reference
    assert not list(target.rglob("*.py*"))


def test_check_reports_missing_outdated_and_current(tmp_path: Path) -> None:
    target = tmp_path / SKILL_NAME
    missing = check(target)
    assert not missing.current
    assert missing.installed is None

    install(target)
    status = check(target)
    assert status.current
    assert status.installed == politefetch.__version__

    old = SKILL.replace(f'version: "{politefetch.__version__}"', 'version: "0.0.1"')
    (target / "SKILL.md").write_text(old, encoding="utf-8")
    outdated = check(target)
    assert not outdated.current
    assert outdated.installed == "0.0.1"
    assert "install" in outdated.message


def test_install_replaces_an_older_copy(tmp_path: Path) -> None:
    target = tmp_path / SKILL_NAME
    install(target)
    (target / "stale.md").write_text("old", encoding="utf-8")
    install(target)
    assert not (target / "stale.md").exists()


def test_install_leaves_other_directories_alone(tmp_path: Path) -> None:
    target = tmp_path / "mine"
    target.mkdir()
    (target / "notes.md").write_text("keep", encoding="utf-8")
    with pytest.raises(FileExistsError):
        install(target)
    assert (target / "notes.md").read_text("utf-8") == "keep"
    install(target, force=True)
    assert not (target / "notes.md").exists()
    assert check(target).current


def test_command_line(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.chdir(tmp_path)
    assert main(["check"]) == 1
    assert "not installed" in capsys.readouterr().out
    assert main(["install"]) == 0
    assert (tmp_path / DEFAULT_TARGET / "SKILL.md").is_file()
    assert politefetch.__version__ in capsys.readouterr().out
    assert main(["check"]) == 0
    assert "current" in capsys.readouterr().out

    other = tmp_path / "other"
    other.mkdir()
    (other / "x").write_text("x", encoding="utf-8")
    assert main(["install", "--target", str(other)]) == 1
    assert "--force" in capsys.readouterr().err
    assert main(["install", "--target", str(other), "--force"]) == 0
    capsys.readouterr()

    assert main(["show"]) == 0
    assert capsys.readouterr().out == SKILL
    assert main(["path"]) == 0
    assert capsys.readouterr().out.strip().endswith(SKILL_NAME)


